"""Writes benchmarks/RESULTS.md from what run.sh collected.

    report.py <raw.txt> <environment.txt> <substitution.txt> <workloads/> <out.md>

raw.txt has one line per run: key=value pairs, as each workload prints them,
plus run= and variant=. The report gives the median of each metric over the
runs, the spread of throughput, and the environment the runs came from.
"""

import pathlib
import statistics
import sys

VARIANTS = ["baseline", "optimized", "direct"]


def parse_pairs(line):
    pairs = {}
    for token in line.split():
        if "=" in token:
            key, value = token.split("=", 1)
            pairs[key] = value
    return pairs


def read_environment(path):
    env = {}
    for line in pathlib.Path(path).read_text().splitlines():
        if "=" in line:
            key, value = line.split("=", 1)
            env[key] = value
    return env


def describe(source):
    """The workload's opening comment, as one paragraph."""
    lines = []
    for line in pathlib.Path(source).read_text().splitlines():
        if not line.startswith("//"):
            break
        text = line[2:].strip()
        if not text:
            break
        lines.append(text)
    return " ".join(lines)


def rate(items_per_sec):
    if items_per_sec >= 1e6:
        return f"{items_per_sec / 1e6:.2f}M"
    return f"{items_per_sec / 1e3:.0f}k"


def duration(ns):
    if ns >= 1e6:
        return f"{ns / 1e6:.2f} ms"
    if ns >= 1e3:
        return f"{ns / 1e3:.2f} µs"
    return f"{ns:.0f} ns"


def main(raw_path, env_path, substitution_path, workloads_dir, out_path):
    runs = {}  # (workload, variant) -> [pairs]
    order = []
    for line in pathlib.Path(raw_path).read_text().splitlines():
        pairs = parse_pairs(line)
        key = (pairs["workload"], pairs["variant"])
        if key not in runs:
            runs[key] = []
            order.append(pairs["workload"])
        runs[key].append(pairs)
    workloads = list(dict.fromkeys(order))

    substitution = dict(
        line.split() for line in pathlib.Path(substitution_path).read_text().splitlines() if line.strip()
    )
    env = read_environment(env_path)

    # A workload that measures latency is paced, so its throughput is its
    # pacing rate and says nothing about the queue.
    paced = [w for w in workloads if any("p50_ns" in r for v in VARIANTS for r in runs.get((w, v), []))]
    unpaced = [w for w in workloads if w not in paced]

    def median(workload, variant, metric):
        values = [float(r[metric]) for r in runs.get((workload, variant), []) if metric in r]
        return statistics.median(values) if values else None

    out = []
    out.append("# Benchmark results")
    out.append("")
    out.append(
        f"Generated by `benchmarks/run.sh` on {env['date']}. Rerun it to update this "
        "file rather than editing it. How the suite works, and what it does not "
        "measure yet, is in `benchmarks/README.md`."
    )
    out.append("")
    out.append("## Environment")
    out.append("")
    out.append("| | |")
    out.append("| --- | --- |")
    out.append(f"| Commit | `{env['commit']}` on `{env['branch']}` |")
    out.append(f"| LLVM pin | `{env['llvm']}` |")
    out.append(f"| CPU | {env['cpu']}, {env['cores']} cores |")
    out.append(f"| Memory | {env['memory']} |")
    out.append(f"| OS | {env['os']} |")
    out.append(f"| Runs | {env['runs']} per variant, interleaved; medians reported |")
    out.append(f"| Threads | {env['pinning']} |")
    out.append("")

    out.append("## Throughput")
    out.append("")
    out.append(
        "Median items per second. The ratios are against baseline, the same "
        "program with `wtc::queue<T>`."
    )
    out.append("")
    out.append("| Workload | Optimized build | baseline | optimized | direct | optimized ÷ baseline | direct ÷ baseline |")
    out.append("| --- | --- | ---: | ---: | ---: | ---: | ---: |")
    for w in unpaced:
        cells = [median(w, v, "items_per_sec") for v in VARIANTS]
        base = cells[0]
        shown = [rate(c) if c else "—" for c in cells]
        ratio_opt = f"{cells[1] / base:.2f}x" if cells[1] and base else "—"
        ratio_dir = f"{cells[2] / base:.2f}x" if cells[2] and base else "—"
        out.append(f"| `{w}` | {substitution.get(w, '?')} | {' | '.join(shown)} | {ratio_opt} | {ratio_dir} |")
    out.append("")

    # A workload the pass must leave alone builds the same queue code twice;
    # how far apart its two builds measure is how much difference this
    # machine produces on its own.
    for w in unpaced:
        if substitution.get(w) != "kept":
            continue
        base = median(w, "baseline", "items_per_sec")
        opt = median(w, "optimized", "items_per_sec")
        if base and opt:
            apart = abs(opt / base - 1) * 100
            out.append(
                f"**Noise.** `{w}` is not substituted, so its baseline and optimized builds "
                f"run the same queue code, and they measured {apart:.0f}% apart. A difference "
                "of that size or less between any two columns here is not evidence of anything."
            )
            out.append("")

    latency_workloads = paced
    if latency_workloads:
        out.append("## Latency")
        out.append("")
        out.append(
            "Time from push to pop, per item: the median over runs of each run's "
            "percentile. The worst case is the median of each run's maximum. These "
            "workloads are paced (see Workloads), so they are not in the throughput tables."
        )
        out.append("")
        out.append("| Workload | Variant | p50 | p99 | p99.9 | max |")
        out.append("| --- | --- | ---: | ---: | ---: | ---: |")
        for w in latency_workloads:
            for v in VARIANTS:
                if (w, v) not in runs:
                    continue
                cells = [median(w, v, m) for m in ("p50_ns", "p99_ns", "p999_ns", "max_ns")]
                out.append(f"| `{w}` | {v} | " + " | ".join(duration(c) for c in cells) + " |")
        out.append("")

    out.append("## Spread")
    out.append("")
    out.append("Throughput over all runs, slowest to fastest, items per second.")
    out.append("")
    out.append("| Workload | Variant | min | median | max |")
    out.append("| --- | --- | ---: | ---: | ---: |")
    for w in unpaced:
        for v in VARIANTS:
            values = sorted(float(r["items_per_sec"]) for r in runs.get((w, v), []))
            if values:
                out.append(f"| `{w}` | {v} | {rate(values[0])} | {rate(statistics.median(values))} | {rate(values[-1])} |")
    out.append("")

    out.append("## Workloads")
    out.append("")
    for w in workloads:
        out.append(f"- **`{w}`**: {describe(pathlib.Path(workloads_dir) / (w + '.cpp'))}")
    out.append("")

    pathlib.Path(out_path).write_text("\n".join(out))


if __name__ == "__main__":
    main(*sys.argv[1:])
